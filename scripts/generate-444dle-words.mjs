import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { readSheet } from "read-excel-file/node";

const NUM_LETTERS = 4;

// Guesses come from the Letterpress word list (github.com/atebits/Words, CC0)
// that reduce already ships. It is made for word games, so it has the plurals
// and variant spellings players try without the acronyms and names.
const DICTIONARY =
  "src/routes/game/reduce/tags/lazy-english-dictionary/words.json";
const VALID = "src/routes/game/444dle/words/valid.json";
// A player's report of a missing word goes here.
const ALSO_VALID = ["vape"];

// Solutions are the guesses that at least MIN_KNOWN of people know, by the word
// prevalence norms: Brysbaert, Mandera, McCormick & Keuleers (2019),
// osf.io/g4xrt, CC BY-NC-SA 4.0.
const PREVALENCE = "https://osf.io/download/nbu9e/";
// Even "a" scores 0.98.
const MIN_KNOWN = 0.97;
const COMMON = "src/routes/game/444dle/words/common.ts";
// Ordinary words that scored just under MIN_KNOWN, and words that only look
// like plurals.
const ALSO_COMMON = [
  "alas",
  "ally",
  "bury",
  "cite",
  "hers",
  "mere",
  "news",
  "onto",
  "oops",
  "ours",
];
// Fine to guess, not to be handed as the answer.
const NOT_COMMON = [
  "anal",
  "anus",
  "boob",
  "butt",
  "cock",
  "coke",
  "crap",
  "cunt",
  "damn",
  "dick",
  "dope",
  "dyke",
  "fart",
  "fuck",
  "john",
  "kink",
  "lube",
  "lust",
  "nude",
  "orgy",
  "pimp",
  "piss",
  "poop",
  "porn",
  "puke",
  "puss",
  "rape",
  "sexy",
  "shag",
  "shit",
  "slut",
  "snot",
  "suck",
];

const root = fileURLToPath(new URL("..", import.meta.url));

const dictionary = new Set(
  JSON.parse(await readFile(join(root, DICTIONARY), "utf8")),
);

const response = await fetch(PREVALENCE);
if (!response.ok) throw new Error(`${PREVALENCE} — ${response.status}`);
const [, ...rows] = await readSheet(Buffer.from(await response.arrayBuffer()));
const known = new Set(
  rows.filter(([, share]) => share >= MIN_KNOWN).map(([word]) => word),
);

// "cars" and "goes", but not "boss" or "plus".
const isPlural = (word) =>
  /[^su]s$/.test(word) &&
  (dictionary.has(word.slice(0, -1)) ||
    (word.endsWith("es") && dictionary.has(word.slice(0, -2))));

const sorted = (words) => [...new Set(words)].sort();

const guesses = [...dictionary].filter((word) => word.length === NUM_LETTERS);
const common = sorted([
  ...guesses.filter(
    (word) => known.has(word) && !isPlural(word) && !NOT_COMMON.includes(word),
  ),
  ...ALSO_COMMON,
]);
const valid = sorted([...guesses, ...common, ...ALSO_VALID]);

await writeFile(join(root, VALID), JSON.stringify(valid));
console.log(`${VALID} — ${valid.length} words`);

await writeFile(
  join(root, COMMON),
  `// Four-letter words nearly everyone knows; today's three solutions are drawn
// from here.
// Generated by \`npm run words\`: edit scripts/generate-444dle-words.mjs.
export default [
${common.map((word) => `  "${word}",\n`).join("")}];
`,
);
console.log(`${COMMON} — ${common.length} words`);
