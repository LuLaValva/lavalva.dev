import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { readSheet } from "read-excel-file/node";

const NUM_LETTERS = 4;

const DICTIONARY =
  "src/routes/game/reduce/tags/lazy-english-dictionary/words.json";
const VALID = "src/routes/game/444dle/words/valid.json";
const ALSO_VALID = ["vape"];

const PREVALENCE = "https://osf.io/download/nbu9e/";
// The share of people who know a word. Even "a" scores 0.98.
const MIN_KNOWN = 0.97;
const COMMON = "src/routes/game/444dle/words/common.ts";
const ALSO_COMMON = [
  "alas",
  "ally",
  "bury",
  "cite",
  "hers",
  "mere",
  "news",
  "onto",
  "oops",
  "ours",
];
const OFFENSIVE = [
  "anal",
  "cock",
  "cunt",
  "dick",
  "dyke",
  "fuck",
  "orgy",
  "piss",
  "porn",
  "rape",
  "shit",
  "slut",
];

const root = fileURLToPath(new URL("..", import.meta.url));

const dictionary = new Set(
  JSON.parse(await readFile(join(root, DICTIONARY), "utf8")),
);

const response = await fetch(PREVALENCE);
if (!response.ok) throw new Error(`${PREVALENCE} — ${response.status}`);
const [, ...rows] = await readSheet(Buffer.from(await response.arrayBuffer()));
const known = new Set(
  rows.filter(([, share]) => share >= MIN_KNOWN).map(([word]) => word),
);

// "cars" and "goes", but not "boss" or "plus".
const isPlural = (word) =>
  /[^su]s$/.test(word) &&
  (dictionary.has(word.slice(0, -1)) ||
    (word.endsWith("es") && dictionary.has(word.slice(0, -2))));

const sorted = (words) => [...new Set(words)].sort();

const guesses = [...dictionary].filter((word) => word.length === NUM_LETTERS);
const common = sorted([
  ...guesses.filter(
    (word) => known.has(word) && !isPlural(word) && !OFFENSIVE.includes(word),
  ),
  ...ALSO_COMMON,
]);
const valid = sorted([...guesses, ...common, ...ALSO_VALID]);

await writeFile(join(root, VALID), JSON.stringify(valid));
console.log(`${VALID} — ${valid.length} words`);

await writeFile(
  join(root, COMMON),
  `// Generated by \`npm run words\`.
export default [
${common.map((word) => `  "${word}",\n`).join("")}];
`,
);
console.log(`${COMMON} — ${common.length} words`);
